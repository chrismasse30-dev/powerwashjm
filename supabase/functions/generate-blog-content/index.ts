import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "npm:@supabase/supabase-js@2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type, Authorization, X-Client-Info, Apikey",
};

// Securely retrieve API key from environment variables
const GEMINI_API_KEY = Deno.env.get("GEMINI_API_KEY");
const GEMINI_API_URL = "https://generativelanguage.googleapis.com/v1/models/gemini-2.0-flash:generateContent";

interface GenerateRequest {
  generationType: 'research' | 'outline' | 'draft' | 'seo_optimize' | 'meta_tags' | 'rewrite';
  topic?: string;
  primaryKeyword?: string;
  tone?: string;
  targetLength?: number;
  existingContent?: string;
  additionalContext?: string;
  blogPostId?: string;
}

Deno.serve(async (req: Request) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { status: 200, headers: corsHeaders });
  }

  try {
    // Validate that the Gemini API key is configured
    if (!GEMINI_API_KEY) {
      console.error('GEMINI_API_KEY is not set in environment variables');
      throw new Error("GEMINI_API_KEY environment variable is not configured. Please set it in Supabase Edge Function secrets.");
    }

    const supabase = createClient(
      Deno.env.get("SUPABASE_URL") ?? "",
      Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? ""
    );

    const authHeader = req.headers.get("Authorization");
    if (!authHeader) {
      throw new Error("Missing authorization header");
    }

    const { data: { user }, error: authError } = await supabase.auth.getUser(
      authHeader.replace("Bearer ", "")
    );

    if (authError || !user) {
      console.error('Auth error:', authError);
      throw new Error("Unauthorized: " + (authError?.message || 'Invalid token'));
    }

    const requestData: GenerateRequest = await req.json();
    const startTime = Date.now();

    const { data: promptTemplate } = await supabase
      .from('ai_prompt_templates')
      .select('*')
      .eq('template_type', requestData.generationType)
      .eq('active', true)
      .order('version', { ascending: false })
      .limit(1)
      .single();

    if (!promptTemplate) {
      throw new Error(`No active prompt template found for type: ${requestData.generationType}`);
    }

    const prompt = buildPrompt(requestData, promptTemplate);

    const geminiResponse = await fetch(`${GEMINI_API_URL}?key=${GEMINI_API_KEY}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [{
          parts: [{ text: prompt }]
        }],
        generationConfig: {
          temperature: promptTemplate.parameters?.temperature || 0.7,
          maxOutputTokens: promptTemplate.parameters?.maxOutputTokens || 8000,
          topP: 0.95,
          topK: 40
        },
        safetySettings: [
          { category: "HARM_CATEGORY_HARASSMENT", threshold: "BLOCK_MEDIUM_AND_ABOVE" },
          { category: "HARM_CATEGORY_HATE_SPEECH", threshold: "BLOCK_MEDIUM_AND_ABOVE" },
          { category: "HARM_CATEGORY_SEXUALLY_EXPLICIT", threshold: "BLOCK_MEDIUM_AND_ABOVE" },
          { category: "HARM_CATEGORY_DANGEROUS_CONTENT", threshold: "BLOCK_MEDIUM_AND_ABOVE" }
        ]
      })
    });

    if (!geminiResponse.ok) {
      const errorText = await geminiResponse.text();
      console.error('Gemini API Error Details:', {
        status: geminiResponse.status,
        statusText: geminiResponse.statusText,
        errorBody: errorText,
        apiUrl: GEMINI_API_URL
      });
      throw new Error(`Gemini API error (${geminiResponse.status}): ${errorText}`);
    }

    const geminiData = await geminiResponse.json();
    console.log('Gemini Response Structure:', {
      hasCandidates: !!geminiData.candidates,
      candidatesLength: geminiData.candidates?.length,
      firstCandidate: geminiData.candidates?.[0] ? 'exists' : 'missing'
    });

    const generatedContent = geminiData.candidates?.[0]?.content?.parts?.[0]?.text || "";

    if (!generatedContent) {
      console.error('No content in Gemini response:', JSON.stringify(geminiData, null, 2));
      throw new Error("No content generated by Gemini. Response structure may have changed.");
    }

    const generationTime = Date.now() - startTime;
    const tokenCount = Math.ceil(generatedContent.length / 4);
    const analysis = await analyzeSEOAndReadability(generatedContent, requestData.primaryKeyword || '');

    const { data: generation, error: insertError } = await supabase
      .from('ai_content_generations')
      .insert({
        blog_post_id: requestData.blogPostId || null,
        generation_type: requestData.generationType,
        prompt_used: prompt,
        input_context: requestData,
        generated_content: generatedContent,
        seo_score: analysis.seoScore,
        readability_grade: analysis.readabilityGrade,
        token_count: tokenCount,
        generation_time_ms: generationTime,
        user_id: user.id
      })
      .select()
      .single();

    if (insertError) {
      console.error("Error storing generation:", insertError);
    }

    return new Response(
      JSON.stringify({
        success: true,
        content: generatedContent,
        analysis: analysis,
        metadata: {
          generationId: generation?.id,
          tokenCount,
          generationTimeMs: generationTime,
          promptTemplateVersion: promptTemplate.version
        }
      }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );

  } catch (error: any) {
    console.error("Error in generate-blog-content:", error);
    return new Response(
      JSON.stringify({ success: false, error: error.message }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});

function buildPrompt(request: GenerateRequest, template: any): string {
  let prompt = template.system_instructions ? `${template.system_instructions}\n\n` : '';

  switch (request.generationType) {
    case 'research':
      prompt += `Research the topic: "${request.topic}"\n\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n\n`;
      prompt += `Provide:\n`;
      prompt += `1. Key points to cover\n`;
      prompt += `2. Related keywords and semantic variations\n`;
      prompt += `3. Common questions people ask\n`;
      prompt += `4. Competitive insights\n`;
      prompt += `5. Content structure recommendations\n`;
      break;

    case 'outline':
      prompt += `Create a blog post outline optimized for 80+ SEO score.\n\n`;
      prompt += `Topic: "${request.topic}"\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n`;
      prompt += `Tone: ${request.tone || 'professional'}\n`;
      prompt += `Target: ${request.targetLength || 1500} words\n\n`;
      prompt += `REQUIRED STRUCTURE FOR HIGH SEO:\n\n`;
      prompt += `1. Title: Include "${request.primaryKeyword}" in title (H2)\n\n`;
      prompt += `2. Introduction (200 words):\n`;
      prompt += `   - Hook with benefit or question\n`;
      prompt += `   - Include keyword once naturally\n`;
      prompt += `   - Preview main sections\n\n`;
      prompt += `3. Main Sections (5-7 H2 headers):\n`;
      prompt += `   - H2: [Section Title with Keyword]\n`;
      prompt += `     * H3: [Specific subtopic]\n`;
      prompt += `     * Key points (bullet list)\n`;
      prompt += `     * Examples/tips to include\n\n`;
      prompt += `   - Include keyword in at least 3 H2 headers\n`;
      prompt += `   - Each H2 should have 2-3 H3 subheaders\n`;
      prompt += `   - Plan for 150-250 words per section\n\n`;
      prompt += `4. Lists & Formatting:\n`;
      prompt += `   - Mark where to add bullet lists (minimum 2)\n`;
      prompt += `   - Note where to use <strong> emphasis\n\n`;
      prompt += `5. Conclusion & CTA (150 words):\n`;
      prompt += `   - Summarize key benefits\n`;
      prompt += `   - Strong call-to-action\n`;
      prompt += `   - Include keyword once\n\n`;
      prompt += `Provide the complete structured outline now:\n`;
      break;

    case 'draft':
      prompt += `Write a complete blog post based on this outline:\n\n`;
      prompt += `${request.existingContent}\n\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n`;
      prompt += `Tone: ${request.tone || 'professional'}\n`;
      prompt += `Target length: ${request.targetLength || 1500} words\n\n`;
      prompt += `CRITICAL REQUIREMENTS - MUST ACHIEVE 80+ SEO SCORE:\n\n`;
      prompt += `1. STRUCTURE (Required for high SEO score):\n`;
      prompt += `   - Start with <h2> for main title (include primary keyword)\n`;
      prompt += `   - Include 5-7 <h2> section headers throughout\n`;
      prompt += `   - Include 3-5 <h3> subheaders under H2 sections\n`;
      prompt += `   - Use <p> tags for all paragraphs\n`;
      prompt += `   - Include at least 2 <ul> or <ol> lists with <li> items\n`;
      prompt += `   - Use <strong> to emphasize key points (3-5 times)\n\n`;
      prompt += `2. KEYWORD OPTIMIZATION (Required):\n`;
      prompt += `   - Include primary keyword "${request.primaryKeyword}" 6-10 times naturally\n`;
      prompt += `   - Place keyword in first H2 header\n`;
      prompt += `   - Place keyword in at least 2 other H2 headers\n`;
      prompt += `   - Use keyword variations and related terms\n\n`;
      prompt += `3. READABILITY (MUST achieve Flesch Score 60+):\n`;
      prompt += `   - Write ONLY short sentences (10-15 words average)\n`;
      prompt += `   - Use simple, common words (avoid complex vocabulary)\n`;
      prompt += `   - Keep paragraphs to 2-3 sentences maximum\n`;
      prompt += `   - Use active voice, not passive\n`;
      prompt += `   - Add transition words: "However," "Therefore," "Additionally," "In fact,"\n\n`;
      prompt += `4. CONTENT LENGTH:\n`;
      prompt += `   - Write ${Math.max(1200, request.targetLength || 1500)} words minimum\n`;
      prompt += `   - Aim for ${request.targetLength || 1500}-${(request.targetLength || 1500) + 300} words\n\n`;
      prompt += `5. ENGAGEMENT:\n`;
      prompt += `   - Start each section with a clear benefit or question\n`;
      prompt += `   - Include specific examples and actionable tips\n`;
      prompt += `   - End with a strong call-to-action\n\n`;
      prompt += `EXAMPLE STRUCTURE:\n`;
      prompt += `<h2>Why [Topic with Keyword] Matters</h2>\n`;
      prompt += `<p>Short intro sentence. Another clear point. Keep it simple.</p>\n`;
      prompt += `<h3>Key Benefit One</h3>\n`;
      prompt += `<p>Explain benefit. Use short words. Make it clear.</p>\n`;
      prompt += `<ul><li>Point one</li><li>Point two</li></ul>\n\n`;
      prompt += `Write the complete blog post now following ALL requirements above:\n`;
      break;

    case 'seo_optimize':
      prompt += `SEO OPTIMIZATION - TARGET: 80+ SEO SCORE\n\n`;
      prompt += `Current content to optimize:\n${request.existingContent}\n\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n\n`;
      prompt += `REQUIRED OPTIMIZATIONS:\n\n`;
      prompt += `1. HEADERS - Add/Fix Structure:\n`;
      prompt += `   - Ensure 5-7 <h2> headers exist\n`;
      prompt += `   - Add 3-5 <h3> subheaders\n`;
      prompt += `   - Include keyword in at least 3 headers\n\n`;
      prompt += `2. KEYWORD OPTIMIZATION:\n`;
      prompt += `   - Add keyword "${request.primaryKeyword}" 6-10 times total\n`;
      prompt += `   - Use variations: add related terms naturally\n`;
      prompt += `   - Maintain 0.8-1.5% keyword density\n\n`;
      prompt += `3. READABILITY - Target Flesch Score 60+:\n`;
      prompt += `   - Break long sentences into 10-15 word sentences\n`;
      prompt += `   - Replace complex words with simple alternatives\n`;
      prompt += `   - Split long paragraphs (max 3 sentences each)\n`;
      prompt += `   - Add transition words between paragraphs\n\n`;
      prompt += `4. STRUCTURE:\n`;
      prompt += `   - Add at least 2 <ul> or <ol> lists if missing\n`;
      prompt += `   - Use <strong> on 3-5 key phrases\n`;
      prompt += `   - Ensure minimum 1200 words\n\n`;
      prompt += `5. ENGAGEMENT:\n`;
      prompt += `   - Add specific examples\n`;
      prompt += `   - Include actionable tips\n`;
      prompt += `   - Strengthen call-to-action at end\n\n`;
      prompt += `Return the COMPLETE optimized HTML content with ALL changes applied:\n`;
      break;

    case 'meta_tags':
      prompt += `Generate SEO meta tags for this blog post:\n\n`;
      prompt += `Title: ${request.topic}\n`;
      prompt += `Content preview: ${request.existingContent?.substring(0, 500)}\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n\n`;
      prompt += `Generate:\n`;
      prompt += `1. SEO Title (50-60 characters, include keyword)\n`;
      prompt += `2. Meta Description (140-160 characters, compelling)\n`;
      prompt += `3. Focus Keyphrase\n`;
      prompt += `4. URL Slug (lowercase, hyphens)\n`;
      prompt += `5. 5-8 relevant tags\n\n`;
      prompt += `Return as JSON: {title, metaDescription, focusKeyphrase, slug, tags}\n`;
      break;

    case 'rewrite':
      prompt += `Rewrite this content to improve quality:\n\n`;
      prompt += `${request.existingContent}\n\n`;
      prompt += `Primary keyword: ${request.primaryKeyword}\n`;
      prompt += `Tone: ${request.tone || 'professional'}\n\n`;
      prompt += `Improve:\n`;
      prompt += `- Clarity and conciseness\n`;
      prompt += `- Engagement and readability\n`;
      prompt += `- SEO optimization\n`;
      prompt += `- Flow and structure\n`;
      prompt += `Maintain HTML formatting.\n`;
      break;
  }

  if (request.additionalContext) {
    prompt += `\n\nAdditional context: ${request.additionalContext}`;
  }

  return prompt;
}

async function analyzeSEOAndReadability(content: string, keyword: string) {
  const wordCount = content.split(/\s+/).length;
  const sentences = content.split(/[.!?]+/).filter(s => s.trim().length > 0);
  const sentenceCount = sentences.length;

  const keywordMatches = (content.match(new RegExp(keyword, 'gi')) || []).length;
  const keywordDensity = (keywordMatches / wordCount) * 100;

  const avgWordsPerSentence = wordCount / sentenceCount;
  const avgSyllablesPerWord = 1.5;
  const fleschScore = 206.835 - (1.015 * avgWordsPerSentence) - (84.6 * avgSyllablesPerWord);

  let readabilityGrade = 'C';
  if (fleschScore >= 80) readabilityGrade = 'A+';
  else if (fleschScore >= 70) readabilityGrade = 'A';
  else if (fleschScore >= 60) readabilityGrade = 'B+';
  else if (fleschScore >= 50) readabilityGrade = 'B';

  let seoScore = 0;

  if (keywordMatches >= 3) seoScore += 20;
  else if (keywordMatches >= 1) seoScore += 10;

  if (keywordDensity >= 0.5 && keywordDensity <= 2.5) seoScore += 15;
  else if (keywordDensity >= 0.3 && keywordDensity <= 3) seoScore += 8;

  if (wordCount >= 1200) seoScore += 15;
  else if (wordCount >= 800) seoScore += 10;
  else if (wordCount >= 500) seoScore += 5;

  const h2Count = (content.match(/<h2/gi) || []).length;
  const h3Count = (content.match(/<h3/gi) || []).length;
  if (h2Count >= 3 && h3Count >= 2) seoScore += 20;
  else if (h2Count >= 2) seoScore += 12;
  else if (h2Count >= 1) seoScore += 6;

  if (fleschScore >= 60) seoScore += 15;
  else if (fleschScore >= 50) seoScore += 10;
  else if (fleschScore >= 40) seoScore += 5;

  const paragraphCount = (content.match(/<p>/gi) || []).length;
  const listCount = (content.match(/<ul>|<ol>/gi) || []).length;
  if (paragraphCount >= 5 && listCount >= 1) seoScore += 15;
  else if (paragraphCount >= 3) seoScore += 10;

  return {
    seoScore: Math.min(100, seoScore),
    readabilityGrade,
    fleschScore: Math.round(fleschScore),
    wordCount,
    keywordDensity: keywordDensity.toFixed(2),
    sentenceCount,
    avgWordsPerSentence: avgWordsPerSentence.toFixed(1)
  };
}